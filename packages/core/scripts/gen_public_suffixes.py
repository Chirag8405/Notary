"""Generate `notary_core/units/_public_suffixes.py` from the vendored Public Suffix List.

Deterministic and offline: the only input is `packages/core/data/public_suffix_list.dat`. This
script lives outside `notary_core` so the package itself stays free of I/O.

Refresh: download https://publicsuffix.org/list/public_suffix_list.dat over the old file, run
`pnpm --filter @notary/core psl:generate`, review the diff and commit both files.
`--check` regenerates in memory and exits 1 when the committed module differs.
"""

import re
import sys
from pathlib import Path

_CORE = Path(__file__).resolve().parent.parent
DATA_PATH = _CORE / "data" / "public_suffix_list.dat"
OUTPUT_PATH = _CORE / "src" / "notary_core" / "units" / "_public_suffixes.py"

_VERSION = re.compile(r"^// VERSION: (\S+)$", re.MULTILINE)
_COMMIT = re.compile(r"^// COMMIT: ([0-9a-f]{40})$", re.MULTILINE)
_BEGIN = {
    "// ===BEGIN ICANN DOMAINS===": "icann",
    "// ===BEGIN PRIVATE DOMAINS===": "private",
}
_END = {"// ===END ICANN DOMAINS===", "// ===END PRIVATE DOMAINS==="}
_PUNYCODE_PREFIX = "xn--"
_HEADER = '''\
"""Public Suffix List snapshot as embedded data. GENERATED, do not edit.

Generated by packages/core/scripts/gen_public_suffixes.py from
packages/core/data/public_suffix_list.dat (pinned snapshot, see PSL_VERSION and PSL_COMMIT).
Regenerate with `pnpm --filter @notary/core psl:generate`; a test fails when this file and the
vendored list disagree.

Source: https://publicsuffix.org/list/public_suffix_list.dat
Licence: Mozilla Public License 2.0, https://mozilla.org/MPL/2.0/ . The list is (c) its
contributors (publicsuffix.org); this module is a data transformation of it (internationalised
labels converted to punycode, one rule per line, sorted) and stays under MPL-2.0. The unmodified
list is vendored next to the core package in data/public_suffix_list.dat.

Rules use the list's own syntax: "a.b" is a suffix, "*.a.b" a wildcard, "!c.a.b" an exception.
The two sections stay separate: ICANN_RULES are delegated TLD registries, PRIVATE_RULES are
suffixes that private parties (github.io, vercel.app, ...) asked to be listed. Egress decisions
use both.
"""
'''


def _ace_label(label: str) -> str:
    if label.isascii():
        return label
    return _PUNYCODE_PREFIX + label.encode("punycode").decode("ascii")


def _ace_rule(rule: str) -> str:
    prefix = ""
    if rule.startswith("!"):
        prefix, rule = "!", rule[1:]
    labels = rule.split(".")
    for index, label in enumerate(labels):
        if label == "*":
            if index != 0 or prefix:
                raise ValueError(f"unsupported wildcard placement in rule {rule!r}")
        elif not label or "*" in label or "!" in label:
            raise ValueError(f"malformed rule {rule!r}")
    return prefix + ".".join(_ace_label(label) for label in labels)


def parse(dat: str) -> tuple[str, str, dict[str, list[str]]]:
    """Return (version, commit, {"icann": rules, "private": rules}) with rules in ACE form."""
    version = _VERSION.search(dat)
    commit = _COMMIT.search(dat)
    if version is None or commit is None:
        raise ValueError("list has no VERSION or COMMIT header")
    sections: dict[str, set[str]] = {"icann": set(), "private": set()}
    current: str | None = None
    for raw in dat.splitlines():
        line = raw.strip()
        if line in _BEGIN:
            current = _BEGIN[line]
        elif line in _END:
            current = None
        elif line and not line.startswith("//"):
            if current is None:
                raise ValueError(f"rule outside a section: {line!r}")
            sections[current].add(_ace_rule(line.split()[0].lower()))
    for name, rules in sections.items():
        if not rules:
            raise ValueError(f"section {name} is empty")
    return version.group(1), commit.group(1), {k: sorted(v) for k, v in sections.items()}


def _render_set(name: str, rules: list[str]) -> str:
    body = "".join(f'        "{rule}",\n' for rule in rules)
    return f"{name}: frozenset[str] = frozenset(\n    {{\n{body}    }}\n)\n"


def render(dat: str) -> str:
    """The full text of the generated module for the list text `dat`."""
    version, commit, sections = parse(dat)
    return (
        _HEADER
        + "\n"
        + f'PSL_VERSION = "{version}"\n'
        + f'PSL_COMMIT = "{commit}"\n'
        + "\n"
        + _render_set("ICANN_RULES", sections["icann"])
        + "\n"
        + _render_set("PRIVATE_RULES", sections["private"])
    )


def main(argv: list[str]) -> int:
    text = render(DATA_PATH.read_text(encoding="utf-8"))
    if "--check" in argv:
        if OUTPUT_PATH.read_text(encoding="utf-8") != text:
            sys.stderr.write("units/_public_suffixes.py is out of date; run psl:generate\n")
            return 1
        return 0
    OUTPUT_PATH.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
