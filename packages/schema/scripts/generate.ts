/**
 * Generates src/generated/{types,zod}.ts from json/notary.schema.json.
 * Never hand-edit the outputs: change the Pydantic models in notary_core instead.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";
import { jsonSchemaToZod } from "json-schema-to-zod";

type JsonSchema = Record<string, unknown>;
type Parse = (schema: JsonSchema) => string | undefined;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(root, "src/generated");
const BANNER =
  "/* eslint-disable */\n// GENERATED by packages/schema/scripts/generate.ts from packages/schema/json.\n// DO NOT EDIT. Change the Pydantic models in notary_core and run `pnpm schema:generate`.\n";

const bundle = JSON.parse(readFileSync(resolve(root, "json/notary.schema.json"), "utf8")) as {
  $defs: Record<string, JsonSchema>;
};
const defs = bundle.$defs;
const names = Object.keys(defs).sort();

function refName(ref: string): string {
  return ref.replace("#/$defs/", "");
}

function collectRefs(node: unknown, out: Set<string>): void {
  if (Array.isArray(node)) {
    node.forEach((item) => {
      collectRefs(item, out);
    });
  } else if (node !== null && typeof node === "object") {
    for (const [key, value] of Object.entries(node)) {
      if (key === "$ref" && typeof value === "string") out.add(refName(value));
      else collectRefs(value, out);
    }
  }
}

function topoSort(): string[] {
  const done = new Set<string>();
  const order: string[] = [];
  const visit = (name: string, trail: string[]): void => {
    if (done.has(name)) return;
    if (trail.includes(name)) throw new Error(`recursive schema: ${[...trail, name].join(" -> ")}`);
    const refs = new Set<string>();
    collectRefs(defs[name], refs);
    [...refs].sort().forEach((ref) => {
      visit(ref, [...trail, name]);
    });
    done.add(name);
    order.push(name);
  };
  names.forEach((name) => {
    visit(name, []);
  });
  return order;
}

async function generateTypes(): Promise<string> {
  const index: JsonSchema = {
    title: "NotarySchemaIndex",
    description: "Index of every model in notary_core, so each is declared exactly once.",
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(names.map((name) => [name, { $ref: `#/$defs/${name}` }])),
    required: names,
    $defs: defs,
  };
  return compile(index, "NotarySchemaIndex", {
    bannerComment: BANNER,
    additionalProperties: false,
    unknownAny: true,
    strictIndexSignatures: false,
    format: false,
  });
}

function generateZod(): string {
  const override: Parse = (schema) => {
    if (typeof schema.$ref === "string") return `${refName(schema.$ref)}Schema`;
    const disc = schema.discriminator as { propertyName?: string } | undefined;
    const options = schema.anyOf as JsonSchema[] | undefined;
    if (disc?.propertyName !== undefined && options !== undefined) {
      const members = options.map((option) => `${refName(String(option.$ref))}Schema`);
      return `z.discriminatedUnion(${JSON.stringify(disc.propertyName)}, [${members.join(", ")}])`;
    }
    return undefined;
  };
  const lines = [BANNER, 'import { z } from "zod";', ""];
  for (const name of topoSort()) {
    const definition = defs[name];
    if (definition === undefined) throw new Error(`missing definition ${name}`);
    const schema = Object.fromEntries(
      Object.entries(definition).filter(([key]) => key !== "title"),
    );
    const expr = jsonSchemaToZod(schema, { module: "none", parserOverride: override });
    lines.push(`export const ${name}Schema = ${expr};`);
    lines.push(`export type ${name} = z.infer<typeof ${name}Schema>;`, "");
  }
  return lines.join("\n");
}

mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "types.ts"), await generateTypes());
writeFileSync(resolve(outDir, "zod.ts"), generateZod());
console.log(`generated ${names.length} types + zod validators`);
